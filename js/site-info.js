export function renderSiteInfo(container, siteId) {
  const info = siteInfo[siteId];
  container.replaceChildren();
  if (!info) return;
  for (const [description, source, label] of [[info.description, info.official],
    [info.access, info.accessSource, "방문 준비"], [info.field, info.report, "현장 후기"]]) {
    if (!description) continue;
    const p = document.createElement("p");
    p.textContent = `${label ? `${label} · ` : ""}${description}`;
    if (source) {
      const link = document.createElement("a");
      link.href = source[1];
      link.textContent = source[0];
      p.append(" ", link);
    }
    container.append(p);
  }
}
